<?php

test('admin products page renders the catalog management workspace', function () {
    $this->get(route('admin.products'))
        ->assertSuccessful()
        ->assertSee('Products')
        ->assertSee('Manage your dessert catalog and inventory.')
        ->assertSee('Search desserts...')
        ->assertSee('All')
        ->assertSee('Shake/Coffee')
        ->assertSee('Pastries')
        ->assertSee('Cakes')
        ->assertSee('Cookies')
        ->assertSee('Add product')
        ->assertSee('Product Details')
        ->assertSee('Upload images')
        ->assertSee('Choose one or more product images')
        ->assertSee('Product name')
        ->assertSee('Description')
        ->assertSee('Category')
        ->assertSee('Price')
        ->assertSee('Stock quantity')
        ->assertSee('Save product')
        ->assertSee('Product grid pagination', false)
        ->assertSee('Products per page')
        ->assertSee('4 products')
        ->assertSee('8 products')
        ->assertSee('12 products')
        ->assertSee('Previous')
        ->assertSee('Next')
        ->assertSee('data-admin-products', false)
        ->assertSee('data-product-grid', false)
        ->assertSee('data-product-search', false)
        ->assertSee('data-product-global-search', false)
        ->assertSee('data-product-filter="all"', false)
        ->assertSee('data-product-filter="shake/coffee"', false)
        ->assertSee('data-product-open-add', false)
        ->assertSee('data-product-modal', false)
        ->assertSee('data-product-form', false)
        ->assertSee('data-product-id', false)
        ->assertSee('data-product-images', false)
        ->assertSee('data-product-image-preview', false)
        ->assertSee('data-product-name', false)
        ->assertSee('data-product-description', false)
        ->assertSee('data-product-category', false)
        ->assertSee('data-product-price', false)
        ->assertSee('data-product-stock', false)
        ->assertSee('data-product-page-size', false)
        ->assertSee('data-product-pagination-status', false)
        ->assertSee('data-product-page-buttons', false)
        ->assertSee('data-product-toast-region', false)
        ->assertSee('href="'.route('admin.products').'" aria-current="page"', false)
        ->assertDontSee('href="'.route('admin.dashboard').'" aria-current="page"', false)
        ->assertDontSee('href="'.route('admin.orders').'" aria-current="page"', false);
});
